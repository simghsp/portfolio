import type { NextConfig } from "next";

// Nonce-based CSP would require every page to render dynamically, which
// throws away static generation for what is otherwise a fully static
// portfolio. Since there's no user input reflected into HTML and no
// third-party scripts beyond Vercel Analytics, 'unsafe-inline' on script-src
// (required for Next's own inline hydration scripts without a nonce) is the
// pragmatic tradeoff Next's own docs recommend for this case. 'unsafe-eval'
// is scoped to development only — React uses eval() there for debugging and
// never in production.
const isDev = process.env.NODE_ENV === "development";

const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self' data:",
  "connect-src 'self' https://va.vercel-scripts.com https://vercel-insights.com",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "object-src 'none'",
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
];

const nextConfig: NextConfig = {
  reactCompiler: true,
  async headers() {
    return [
      {
        source: "/:path*",
        headers: securityHeaders,
      },
    ];
  },
};

export default nextConfig;
